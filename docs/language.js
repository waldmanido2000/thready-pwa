let language = localStorage.getItem('thready-language') === 'en' ? 'en' : 'he';
function tr(key, fields = {}) {
  return (language === 'he' ? hebrew[key] || key : key).replace(/\{(\w+)\}/g,
    (slot,name) => Object.prototype.hasOwnProperty.call(fields,name) ? fields[name] : slot);
}
function errorText(message) {
  const field = /^Check the (.+) field\.$/.exec(message);
  const labels = {title:'Title',username:'User ID',name:'Display name',text:'Message',label:'Device name'};
  return field ? tr('Check the {field} field.',{field:tr(labels[field[1]] || field[1])}) : tr(message);
}
